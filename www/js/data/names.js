// Wraps any integer into the 0–98 range, so the cycle restarts after the 99th
// name and keeps working for positions counted past a full pass.
export function getNameByIndex(index) {
  const wrapped = ((Math.trunc(index) % NAMES_COUNT) + NAMES_COUNT) % NAMES_COUNT;
  return NAMES_OF_ALLAH[wrapped];
}
